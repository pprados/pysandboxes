# Parsed rule format used internally:
class SocketMask(NamedTuple):
    families: List[str]
    types: List[int]
    network: Union[IPv4Network, IPv6Network]
    ports: Union[List[int], range]


class SocketRule(NamedTuple):
    action: str
    mask: SocketMask
    direction: str
    config: ConfigLine


SocketRules = Tuple[SocketRule, ...]


