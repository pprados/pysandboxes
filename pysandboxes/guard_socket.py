def _convert_ports_range(syntax: str) -> Union[List[int], range]:
    """
    Converts a port specification string (e.g., "80,443,8000-8080,*")
    into a sorted list of unique integer port numbers or a range object for '*'.

    Args:
        syntax: The port specification string.

    Returns:
        A sorted list of integers representing individual ports and expanded ranges,
        or a range(0, 65535) if '*' is specified. Returns an empty list for invalid syntax.
    """
    max_port = 65535  # Maximum valid port number
    if not syntax:
        return []
    if syntax.strip() == '*':
        return range(max_port + 1)  # Represents all ports
    ports = set()
    elements = syntax.split(',')
    for element in elements:
        element = element.strip()
        if not element:
            continue
        if '-' in element:
            limits = element.split('-', 1)
            if len(limits) == 2:
                start_str, end_str = limits[0].strip(), limits[1].strip()
                if not start_str:
                    raise ValueError(
                        f"Invalid range format: '{element}'. Range start cannot be empty.")
                try:
                    start = int(start_str)
                except ValueError:
                    raise ValueError(
                        f"Invalid start port number '{start_str}' in range '{element}'.")
                if not (0 <= start <= max_port):
                    raise ValueError(
                        f"Start port {start} in range '{element}' is out of valid range (0-{max_port}).")

                if end_str == '':  # Handles open-ended ranges like "8000-"
                    end = max_port
                else:
                    try:
                        end = int(end_str)
                    except ValueError:
                        raise ValueError(
                            f"Invalid end port number '{end_str}' in range '{element}'.")
                    if not (0 <= end <= max_port):
                        raise ValueError(
                            f"End port {end} in range '{element}' is out of valid range (0-{max_port}).")
                if start == end:
                    ports.add(start)
                elif start <= end:
                    ports.add(range(start, end + 1))
                else:
                    raise ValueError(
                        f"Invalid range: start port {start} is greater than end port {end} in '{element}'.")
            else:
                raise ValueError(
                    f"Invalid range format: '{element}'. Unexpected hyphen usage.")
        else:
            try:
                port = int(element)
                if not (0 <= port <= max_port):
                    raise ValueError(
                        f"Port number {port} in '{element}' is out of valid range (0-{max_port}).")
                ports.add(port)
            except ValueError:
                raise ValueError(f"Invalid port number '{element}'.")
    if len(ports) == 1:
        first = next(iter(ports))
        if isinstance(first, range):
            return first
    list_port = set()
    for port in ports:
        if isinstance(port, range):
            list_port.update(list(port))
        else:
            list_port.add(port)
    return sorted(list_port)


def _check_address_with_rules(
        socket_rules: SocketRules,
        socket_instance_type: int,
        address: Tuple[str, int],  # Expect (hostname_or_ip_str, port_int)
        conn_direction: str):  # Expect IN or OUT constants
    """
    Checks if a given address and port are allowed for the specified connection direction
    based on the configured socket_rules and the derived implicit default policy.
    (Docstring needs update for new socket_instance_family, socket_instance_proto args)
    """
    logger.debug(
        "_check_address_with_rules(address=%s, conn_direction=%s, type=%s)",
        address, conn_direction, socket_instance_type)
    hostname, destination_port = address

    if not isinstance(destination_port, int) or not (
            0 <= destination_port <= 65535):
        raise ValueError(f"Invalid port number: {destination_port}")

    try:
        # Resolve hostname to IP addresses using the socket instance's family, type, and proto
        infos = socket.getaddrinfo(hostname, None,
                                   type=socket_instance_type)
    except socket.gaierror:
        # Fallback if the specific proto causes issues, try with proto=0 (OS default for family/type)
        # This might happen if self.proto is something specific but getaddrinfo needs a more general hint
        try:
            logger.debug(
                "getaddrinfo failed with specific proto %s, retrying with proto=0")
            infos = socket.getaddrinfo(hostname, None,
                                       type=socket_instance_type, proto=0)
        except socket.gaierror:
            raise ValueError(
                f"Invalid hostname or IP address (resolution failed): {hostname}")

    # %% Analyse ips
    ip_objects = []
    for res_family, _, _, _, sockaddr in infos:
        # sockaddr[0] is the IP address string
        addr_str = sockaddr[0]
        ip_objects.append(ipaddress.ip_address(addr_str))

    unique_ips = list(dict.fromkeys(ip_objects))
    if not unique_ips:
        raise ValueError(
            f"Invalid hostname or IP address (resolution failed): {hostname}")
    # if not socket_rules:  # FIXME: remove
    #     logger.info(
    #         "Connection to %s port %s ALLOWED because no socket_rules are set.",
    #         hostname, destination_port
    #     )
    #     return

    # %% Analyse socket_rules
    order_apply = (DENY, ALLOW)

    for rule_type_to_check in (DENY, ALLOW):
        for ip_host in unique_ips:
            for (action,
                 (rule_families, rule_types, network_obj, rule_ports_list),
                 rule_direction_from_rule,
                 config) in socket_rules:
                if action == rule_type_to_check:
                    type_match = (not rule_types) or (
                            socket_instance_type in rule_types)

                    if type_match:
                        if rule_direction_from_rule == conn_direction:
                            if ip_host in network_obj and destination_port in rule_ports_list:

                                pysandboxes_logger.info(
                                    "Connection to '%s' (%s:%s) %s by explicit "
                                    "rule '%s' from %s",
                                    hostname, ip_host, destination_port, action,
                                    config.rule, format_ruleref(config)
                                )
                                if action == DENY:
                                    raise SocketRulesError(
                                        f"Guard network connection to "
                                        f"'{hostname}' ({ip_host}:{destination_port}) "
                                        f"{action} by rule "
                                        f"'{config.rule}' "
                                        f"from {format_ruleref(config)})."
                                    )
                                elif action == ALLOW:
                                    raise SocketRulesError(
                                        f"Guard network connection to "
                                        f"'{hostname}' ({ip_host}:{destination_port}) "
                                        f"{action} by rule "
                                        f"'{config.rule}' from {format_ruleref(config)})."
                                    )
    pysandboxes_logger.info(
        "Connection to '%s' (%s:%s) "
        "DENIED by implicit default policy.",
        hostname, unique_ips, destination_port
    )
    raise SocketRulesError(
        f"Guard network connection to '{hostname}' "
        f"({unique_ips}:{destination_port}) "
        f"DENIED by implicit default policy."
    )


