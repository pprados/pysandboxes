# IMPORTANT: This module must be imported *before* any other modules that might
# use the standard `socket` library in your application's main entry point.
#
# Purpose:
# This module patches the standard `socket.socket` class with a custom
# `Guard_socket` class. Its primary role is to intercept and protect network
# socket calls made by Python code using the standard `socket` interface.
#
# Activation:
# The patching happens automatically when this module is imported. To ensure
# that all subsequent uses of `socket.socket` throughout your application
# (including those within third-party libraries) are guarded, this import
# MUST occur before those modules are imported.
#
# Scope of Protection:
# This guard protects against direct socket usage via the Python `socket`
# module. It is designed to mitigate risks from potentially malicious or
# unintended network access originating from Python code, such as code
# generated by an LLM.
#
# Limitations:
# This protection is easily bypassable. It does NOT protect against:
# - Network calls made by native shared libraries (e.g., C/C++ code) invoked
#   by Python.
# - Network calls made by child processes spawned by the Python application.
# - Other forms of inter-process communication.
#
# Nature of Security:
# This is a best-effort security layer within the Python process itself. It
# is NOT a robust security boundary like a firewall, containerization, or
# OS-level sandboxing. It is intended to limit the attack surface specifically
# from potentially untrusted Python code executed within the same process.
#
# Example Usage (in your main application file, e.g., main.py):
