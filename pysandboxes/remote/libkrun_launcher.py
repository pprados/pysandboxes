"""Micro-VM launcher subprocess for the libkrun provider.

This module is launched as a subprocess on the host to configure and start
a libkrun micro-VM instance. It sets up virtio-fs file shares, serial console,
vsock port forwarding, and starts the guest main_sandbox process.
"""

from __future__ import annotations

import ctypes
import json
import logging
import os
import shlex
import socket
import subprocess
import sys
import traceback
from pathlib import Path
from typing import Any

from .libkrun_ffi import (
    LibkrunFFI,
    check_krun_result,
    make_krun_bytes,
    make_krun_str,
)
from .tools import set_pdeathsig

logger = logging.getLogger(__name__)

GUEST_SYSTEM_PYTHON = "/usr/bin/python3"
GUEST_RUN_DIR = "/tmp/pysb_run"
LISTENER_SHIM_NAME = "vsock_listen.py"
READY_FILE_NAME = "ready"
STDOUT_FILE_NAME = "guest.out"
ERROR_FILE_NAME = "launcher.err"
STDIN_FILE_NAME = "guest.in"
MICROVM_FAILED = 70
STDERR_FILE_NAME = "guest.err"
GUEST_SOCKET = "/tmp/pysb_guest.sock"

# Runs under the guest's system Python: the interpreter of a venv may be built without AF_VSOCK, so this one
# accepts the vsock connections and relays them to the Unix socket the guest command listens on, and reports the
# command's exit status. ``READY_FILE_NAME`` tells the host the listener exists, because libkrun aborts when a
# host connection reaches a vsock port nobody listens on.
LISTENER_SHIM = f"""\
import os
import socket
import sys
import threading

port = int(sys.argv[1])
command = sys.argv[sys.argv.index("--") + 1:]
listener = socket.socket(socket.AF_VSOCK, socket.SOCK_STREAM)
listener.bind((socket.VMADDR_CID_ANY, port))
listener.listen(socket.SOMAXCONN)
pid = os.fork()
if pid == 0:
    listener.close()
    os.execv(command[0], command)
with open("{GUEST_RUN_DIR}/{READY_FILE_NAME}", "w") as ready:
    ready.write("1")


def pump(source, target):
    try:
        while data := source.recv(65536):
            target.sendall(data)
    except OSError:
        pass
    try:
        target.shutdown(socket.SHUT_WR)
    except OSError:
        pass


def relay(connection):
    upstream = socket.socket(socket.AF_UNIX)
    try:
        upstream.connect("{GUEST_SOCKET}")
    except OSError:
        connection.close()
        return
    back = threading.Thread(target=pump, args=(upstream, connection), daemon=True)
    back.start()
    pump(connection, upstream)
    back.join()
    connection.close()
    upstream.close()


def accept_loop():
    while True:
        connection, _ = listener.accept()
        threading.Thread(target=relay, args=(connection,), daemon=True).start()


threading.Thread(target=accept_loop, daemon=True).start()
_, status = os.waitpid(pid, 0)
os._exit(os.waitstatus_to_exitcode(status) % 256)
"""


def generate_guest_init_script(
    run_dir: str,
    guest_cmd: list[str],
    mounts: list[dict[str, Any]],
    envs: dict[str, str],
    vsock_port: int = 0,
    capture_output: bool = False,
    cwd: str | None = None,
    net: dict[str, str] | None = None,
    stdin: bool = False,
) -> str:
    """Generate the shell script executed as PID 1 inside the micro-VM.

    With a ``vsock_port``, the guest command is started by the listener shim, which hands it the vsock listener.
    """
    lines = [
        "#!/bin/sh",
        "# Micro-VM guest init script generated by PySandboxes libkrun launcher",
        "export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
        "mount -t proc proc /proc 2>/dev/null",
        "mount -t devtmpfs devtmpfs /dev 2>/dev/null",
        "mount -t sysfs sysfs /sys 2>/dev/null",
        "mount -t tmpfs tmpfs /tmp 2>/dev/null",
        "mkdir -p /tmp/pysb_run 2>/dev/null",
        "mount -t virtiofs pysb_run /tmp/pysb_run 2>/dev/null",
    ]

    # Mount explicit virtio-fs shares
    for m in mounts:
        tag = m["tag"]
        guest_path = m.get("guest_path")
        if guest_path and tag != "pysb_run" and tag != "/dev/root":
            lines.append(f"mkdir -p {shlex.quote(guest_path)} 2>/dev/null")
            lines.append(f"mount -t virtiofs {shlex.quote(tag)} {shlex.quote(guest_path)} 2>/dev/null")

    lines.append("ip link set lo up 2>/dev/null")
    if net:
        lines.extend(
            [
                "ip link set eth0 up 2>/dev/null",
                f"ip addr add {net['address']}/{net['prefix']} dev eth0 2>/dev/null",
                f"ip route add default via {net['gateway']} 2>/dev/null",
                f"echo 'nameserver {net['dns']}' > /tmp/resolv.conf",
                "mount --bind /tmp/resolv.conf /etc/resolv.conf 2>/dev/null",
            ]
        )
    if cwd:
        quoted_cwd = shlex.quote(cwd)
        lines.append(f"cd {quoted_cwd} 2>/dev/null || {{ mkdir -p {quoted_cwd} && cd {quoted_cwd}; }} 2>/dev/null")

    # Quote and execute the guest command
    if vsock_port:
        guest_cmd = [GUEST_SYSTEM_PYTHON, f"{GUEST_RUN_DIR}/{LISTENER_SHIM_NAME}", str(vsock_port), "--", *guest_cmd]
    # The kernel hands its own variables (HOME, TERM) to init: the command gets only the ones the rules allow.
    clean_env = [f"{key}={shlex.quote(str(val))}" for key, val in envs.items()]
    cmd_str = " ".join(["env", "-i", *clean_env, *(shlex.quote(c) for c in guest_cmd)])
    cmd_str += f" < {GUEST_RUN_DIR}/{STDIN_FILE_NAME}" if stdin else " < /dev/null"
    lines.extend(
        [
            (
                f"{cmd_str} > {GUEST_RUN_DIR}/{STDOUT_FILE_NAME} 2> {GUEST_RUN_DIR}/{STDERR_FILE_NAME}"
                if capture_output
                else f"{cmd_str} > {GUEST_RUN_DIR}/guest.log 2>&1"
            ),
            "rc=$?",
            'echo -n "$rc" > /tmp/pysb_run/exitcode',
            "sync",
            "cat /tmp/pysb_run/exitcode > /dev/console",
            "sync",
            "reboot -f",
        ]
    )
    return "\n".join(lines) + "\n"


def run_launcher(config_path: str, guest_args: list[str] | None = None) -> None:
    """Read the launcher configuration file, initialize libkrun, and run the micro-VM."""
    guest_args = guest_args or []
    with open(config_path, encoding="utf-8") as f:
        config = json.load(f)

    vcpus = int(config.get("vcpus", 1))
    ram_mib = int(config.get("ram_mib", 512))
    root_dir = config.get("root_dir", "/")
    run_dir = config["run_dir"]
    unix_socket = config.get("unix_socket")
    port = int(config.get("port", 0)) if unix_socket else 0
    net = config.get("net")
    net_fd = None
    if net:
        guest_side, passt_side = socket.socketpair(socket.AF_UNIX, socket.SOCK_STREAM)
        # The network stack runs in the private, filtered namespace the host prepared; the micro-VM stays out of it.
        subprocess.Popen(
            net["cmd"],
            env={**net.get("env", {}), "PASST_FD": str(passt_side.fileno())},
            pass_fds=(passt_side.fileno(),),
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            preexec_fn=set_pdeathsig,  # noqa: PLW1509
        )
        passt_side.close()
        net_fd = guest_side.fileno()
    mounts = config.get("mounts", [])
    guest_cmd = [*config.get("guest_cmd", []), *(_guest_path(arg, run_dir) for arg in guest_args)]
    envs = config.get("envs", {})

    os.makedirs(run_dir, exist_ok=True)
    guest_init_path = os.path.join(run_dir, "libkrun_guest_init.sh")
    has_stdin = os.path.isfile(os.path.join(run_dir, STDIN_FILE_NAME))
    with open(guest_init_path, "w", encoding="utf-8") as f:
        f.write(
            generate_guest_init_script(
                run_dir,
                guest_cmd,
                mounts,
                envs,
                port,
                capture_output=not unix_socket,
                cwd=os.getcwd(),
                net=net,
                stdin=has_stdin,
            )
        )
    os.chmod(guest_init_path, 0o755)
    Path(run_dir, LISTENER_SHIM_NAME).write_text(LISTENER_SHIM, encoding="utf-8")

    ffi = LibkrunFFI()
    lib = ffi.lib
    err = ctypes.c_void_p(0)

    # 1. Load kernel/firmware payload
    payload = lib.krun_payload_load_krunfw(ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_payload_load_krunfw")

    # 2. Append kernel cmdline
    k_cmd, _ = make_krun_str(f" root=/dev/root init={guest_init_path}")
    lib.krun_payload_append_cmdline(payload, k_cmd)

    # 3. Create and configure VMM builder
    builder_val = lib.krun_vmm_builder_new()
    builder_handle = ctypes.c_void_p(builder_val)

    res_vcpu = lib.krun_vmm_builder_vcpus(ctypes.byref(builder_handle), vcpus, ctypes.byref(err))
    check_krun_result(lib, res_vcpu, err, "krun_vmm_builder_vcpus")

    res_ram = lib.krun_vmm_builder_ram_mib(ctypes.byref(builder_handle), ram_mib, ctypes.byref(err))
    check_krun_result(lib, res_ram, err, "krun_vmm_builder_ram_mib")

    lib.krun_vmm_builder_payload(ctypes.byref(builder_handle), payload)

    # 4. Device Manager setup
    mmio = lib.krun_mmio_device_manager_new()

    # Root filesystem (read-only)
    k_root_tag, _ = make_krun_str("/dev/root")
    k_root_path, _ = make_krun_str(root_dir)
    root_fs = lib.krun_fs_device_new_read_only(k_root_tag, k_root_path, ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_fs_device_new_read_only(rootfs)")
    lib.krun_device_manager_add(mmio, root_fs, ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_device_manager_add(rootfs)")

    # Run directory filesystem (read-write)
    k_run_tag, _ = make_krun_str("pysb_run")
    k_run_path, _ = make_krun_str(run_dir)
    run_fs = lib.krun_fs_device_new(k_run_tag, k_run_path, ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_fs_device_new(pysb_run)")
    lib.krun_device_manager_add(mmio, run_fs, ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_device_manager_add(pysb_run)")

    # Additional virtio-fs mounts
    for m in mounts:
        tag = m["tag"]
        host_path = m["host_path"]
        k_tag, _ = make_krun_str(tag)
        k_path, _ = make_krun_str(host_path)
        if m.get("readonly", False):
            fs_dev = lib.krun_fs_device_new_read_only(k_tag, k_path, ctypes.byref(err))
        else:
            fs_dev = lib.krun_fs_device_new(k_tag, k_path, ctypes.byref(err))
        check_krun_result(lib, 0, err, f"krun_fs_device_new({tag})")
        lib.krun_device_manager_add(mmio, fs_dev, ctypes.byref(err))
        check_krun_result(lib, 0, err, f"krun_device_manager_add({tag})")

    # Console device
    cb = lib.krun_console_device_builder()
    res_con = lib.krun_console_builder_add_default_console(cb, 0, 1, 2, ctypes.byref(err))
    check_krun_result(lib, res_con, err, "krun_console_builder_add_default_console")
    console_dev = lib.krun_console_builder_build(cb, ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_console_builder_build")
    lib.krun_device_manager_add(mmio, console_dev, ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_device_manager_add(console)")

    # Vsock port forwarding (if requested)
    if port > 0:
        vsock = lib.krun_vsock_device_new(3, 0, ctypes.byref(err))
        check_krun_result(lib, 0, err, "krun_vsock_device_new")
        k_sock, _ = make_krun_str(unix_socket)
        res_pf = lib.krun_vsock_device_add_unix_port(vsock, port, k_sock, True)
        check_krun_result(lib, res_pf, err, "krun_vsock_device_add_unix_port")
        lib.krun_device_manager_add(mmio, vsock, ctypes.byref(err))
        check_krun_result(lib, 0, err, "krun_device_manager_add(vsock)")

    # Network device (if requested): the host side of the user-space stack that filters and relays the traffic
    if net_fd is not None:
        k_net_id, _ = make_krun_str("net0")
        k_mac, _ = make_krun_bytes(b"\x5a\x94\xef\xe4\x0c\xee")
        net_dev = lib.krun_net_device_new_unixstream_fd(k_net_id, net_fd, k_mac, 0, ctypes.byref(err))
        check_krun_result(lib, 0, err, "krun_net_device_new_unixstream_fd")
        lib.krun_device_manager_add(mmio, net_dev, ctypes.byref(err))
        check_krun_result(lib, 0, err, "krun_device_manager_add(net)")

    # 5. Attach devices and build VMM
    lib.krun_vmm_builder_devices(ctypes.byref(builder_handle), mmio)
    vmm = lib.krun_vmm_builder_build(ctypes.byref(builder_handle), ctypes.byref(err))
    check_krun_result(lib, 0, err, "krun_vmm_builder_build")

    # 6. Execute micro-VM
    lib.krun_vmm_run(vmm)


def collect_result(run_dir: str) -> int:
    """Replay the guest output on this process's streams and return the guest exit code."""
    for name, stream in ((STDOUT_FILE_NAME, sys.stdout), (STDERR_FILE_NAME, sys.stderr)):
        captured = os.path.join(run_dir, name)
        if os.path.isfile(captured):
            stream.flush()
            stream.buffer.write(Path(captured).read_bytes())
            stream.buffer.flush()
    exitcode_file = os.path.join(run_dir, "exitcode")
    if os.path.isfile(exitcode_file):
        try:
            return int(Path(exitcode_file).read_text(encoding="utf-8").strip())
        except (ValueError, OSError):
            pass
    error_file = os.path.join(run_dir, ERROR_FILE_NAME)
    detail = Path(error_file).read_text(encoding="utf-8") if os.path.isfile(error_file) else ""
    print(f"libkrun: the micro-VM ended without the guest reporting an exit code. {detail}", file=sys.stderr)
    return MICROVM_FAILED


def _guest_path(arg: str, run_dir: str) -> str:
    """Map a host path under the run directory to where the guest sees that directory."""
    return GUEST_RUN_DIR + arg[len(run_dir) :] if arg.startswith(run_dir) else arg


def main() -> None:
    """CLI entry point: ``--config FILE`` then the arguments of the guest program, which the launcher appends.

    ``krun_vmm_run`` ends the whole process when the guest stops, so the VM runs in a child and this process,
    which outlives it, reports the guest's output and exit code.
    """
    argv = sys.argv[1:]
    if len(argv) < 2 or argv[0] != "--config":
        sys.exit("usage: python -m pysandboxes.remote.libkrun_launcher --config FILE [guest arguments...]")
    with open(argv[1], encoding="utf-8") as f:
        run_dir = json.load(f)["run_dir"]
    if "-" in argv[2:] and not sys.stdin.isatty():
        # The guest has no terminal: the script the host reads on its standard input travels in a file.
        Path(run_dir, STDIN_FILE_NAME).write_bytes(sys.stdin.buffer.read())
    child = os.fork()
    if child == 0:
        set_pdeathsig()
        try:
            run_launcher(argv[1], argv[2:])
        except BaseException:  # noqa: BLE001
            Path(run_dir, ERROR_FILE_NAME).write_text(traceback.format_exc(), encoding="utf-8")
            os._exit(1)
        os._exit(0)
    _, status = os.waitpid(child, 0)
    result = collect_result(run_dir)
    sys.exit(result if os.waitstatus_to_exitcode(status) == 0 else MICROVM_FAILED)


if __name__ == "__main__":
    main()
